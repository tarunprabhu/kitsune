#include "kitsune/Core/EmbUtils.h"
#include "kitsune/Core/GlobalVariableUtils.h"
#include "kitsune/Core/TTOptions.h"
#include "kitsune/Core/Tapir.h"
#include "kitsune/Support/CommandLineUtils.h"
#include "llvm/Bitcode/BitcodeWriter.h"
#include "llvm/CodeGen/CommandFlags.h"
#include "llvm/IR/Module.h"
#include "llvm/IRReader/IRReader.h"
#include "llvm/Support/CommandLine.h"
#include "llvm/Support/FileSystem.h"
#include "llvm/Support/InitLLVM.h"
#include "llvm/Support/SourceMgr.h"
#include "llvm/Support/SystemUtils.h"
#include "llvm/Support/TargetSelect.h"
#include "llvm/Support/ToolOutputFile.h"
#include "llvm/Support/WithColor.h"
#include "llvm/Support/raw_ostream.h"

using namespace llvm;
using namespace llvm::sys;

static cl::OptionCategory catKitMBC("kit-mbc options");

static cl::opt<bool> clForce("f", cl::desc("Force binary output on terminals"),
                             cl::cat(catKitMBC));

static cl::opt<std::string>
    clOutFile("o", cl::desc("The file to which to write the extracted module"),
              cl::value_desc("filename"), cl::cat(catKitMBC));

static cl::opt<bool> clOutputAssembly("S",
                                      cl::desc("Write output as LLVM assembly"),
                                      cl::cat(catKitMBC));

static cl::opt<std::string> clInFile(cl::Positional,
                                     cl::desc("<input bitcode file>"),
                                     cl::init("-"), cl::value_desc("filename"),
                                     cl::cat(catKitMBC));

static void writeModule(Module &m, raw_ostream &os) {
  if (clOutputAssembly)
    os << m;
  else
    WriteBitcodeToFile(m, os);
}

static void setupCommandLineOptions() {
  // We need this because the constructor of the TTOptions object reads
  // the -fp-contract option which requires registering the codegen flags.
  static codegen::RegisterCodeGenFlags cgf;

  cl::HideUnrelatedOptions(catKitMBC);

  StringRef optTapir = "tapir";
  clSetOptionVisible(optTapir);
  clSetOptionDescription(optTapir,
                         "Extract bitcode generated by this tapir target");
}

int main(int argc, char *argv[]) {
  InitLLVM X(argc, argv);

  setupCommandLineOptions();
  cl::ParseCommandLineOptions(
      argc, argv,
      "Extract embedded bitcode from an LLVM IR module generated by Kitsune\n");

  InitializeAllAsmPrinters();
  InitializeAllAsmParsers();

  // Write the extracted module to stdout by default. Otherwise, if a file has
  // been provided, we will write the extracted module there as long as there is
  // exactly one embedded bitcode module in the host module.
  std::error_code ec;
  StringRef outFile = clOutFile.empty() ? StringRef("-") : StringRef(clOutFile);
  fs::OpenFlags flags = clOutputAssembly ? fs::OF_TextWithCRLF : fs::OF_None;
  std::unique_ptr<ToolOutputFile> outf(new ToolOutputFile(outFile, ec, flags));
  if (ec) {
    errs() << ec.message() << '\n';
    return 1;
  }

  LLVMContext ctx;
  SMDiagnostic err;
  std::unique_ptr<Module> hostM = parseIRFile(clInFile, err, ctx);
  if (!hostM) {
    err.print(argv[0], errs());
    return 1;
  }

  // If a specific tapir target has been provided, only extract bitcode
  // generated by that target. It is possible for a single tapir target to
  // generate multiple bitcode files. First collect the global variables
  // containing embedded bitcode.
  std::optional<TTOptions> tto =
      TTOptions::createFromSharedCommandLineOptions();
  std::vector<GlobalVariable *> gs;
  if (tto) {
    TTID tt = tto->getTTID();
    for (GlobalVariable &g : hostM->globals()) {
      if (g.hasAttribute(Attribute::KitBC)) {
        assert(g.hasAttribute(Attribute::KitTT) &&
               "Attribute 'kit_bc' requires 'kit_tt");
        if (getAttrValueAsTTID(g, Attribute::KitTT) == tt)
          gs.push_back(&g);
      }
    }
  } else {
    for (GlobalVariable &g : hostM->globals()) {
      if (g.hasAttribute(Attribute::KitBC)) {
        assert(g.hasAttribute(Attribute::KitTT) &&
               "Attribute 'kit_bc' requires 'kit_tt");
        if (g.hasAttribute(Attribute::KitTT))
          gs.push_back(&g);
      }
    }
  }

  // Now parse those into modules.
  std::vector<std::unique_ptr<Module>> embs;
  for (GlobalVariable *g : gs) {
    Expected<std::unique_ptr<Module>> embMOrErr = parseEmbBCGlobal(*g);
    if (not embMOrErr) {
      WithColor::error() << toString(embMOrErr.takeError()) << "\n";
      return 2;
    }
    embs.emplace_back(std::move(*embMOrErr));
  }

  bool outputToStdout = outf->getFilename() == "-";
  raw_ostream &os = outf->os();
  if (embs.empty()) {
    WithColor::warning() << "no embedded bitcode modules found\n";
  } else if (not outputToStdout and embs.size() > 1) {
    // We are writing to a file, but we cannot write more than one module to
    // the file. The likely common case is that there is only embedded module in
    // the input file, so the user may expect that the resulting file can just
    // be used by the LLVM tools. If there are multiple modules, the output
    // from the terminal can still be redirected to a file.
    WithColor::error() << "cannot write " << embs.size()
                       << " embedded modules to a single output file\n";
    return 3;
  } else if (not outputToStdout) {
    // There is only a single embedded bitcode module that is being written to
    // file. Ensure that the file is not deleted after it has been written.
    writeModule(*embs.front(), os);
    outf->keep();
  } else if (clOutputAssembly or clForce or
             not CheckBitcodeOutputToConsole(os)) {
    // We are writing to the terminal. Don't write binary output to it unless
    // the user insists on it.
    for (const auto &m : embs)
      writeModule(*m, os);
  }

  return 0;
}
