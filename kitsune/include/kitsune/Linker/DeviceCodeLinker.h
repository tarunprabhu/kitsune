#ifndef KITSUNE_LINKER_DEVICE_CODE_LINKER_H
#define KITSUNE_LINKER_DEVICE_CODE_LINKER_H

#include "kitsune/Core/Tapir.h"
#include "kitsune/Object/EmbDeviceCodes.h"
#include "llvm/ADT/MapVector.h"
#include "llvm/ADT/SetVector.h"
#include "llvm/ADT/StringSet.h"
#include "llvm/Support/Error.h"

namespace llvm {

namespace object {
class Archive;
class Binary;
class MemoryBuffer;
class ObjectFile;
} // namespace object

/// Link embedded device code. This is intended to be used in LLD or other
/// kitsune-specific utilities. This is mainly intended to be a "helper" class
/// to manage the object files (which may be relocatable object files, static
/// archives or shared libraries) that are provided to tools such as kit-linkdc
/// or lld. The actual linking is likely to be carried out by an external
/// utility such as nvlink.
class DeviceCodeLinker {
public:
  /// The result of linking the embedded device code. One such object will be
  /// returned for each tapir target that generated embedded device code in the
  /// input files.
  struct Result {
    /// The identifier that determines the binary format of the result and its
    /// target architecture.
    const EmbDeviceCode::Id id;

    /// The buffer containing the linked result.
    const std::unique_ptr<MemoryBuffer> buf;
  };

private:
  /// The tapir target id
  TTID tt;

  /// The input files that have been seen. Since we only process every input
  /// file once, this ensures that we ignore those that we have already seen.
  StringSet binFiles;

  /// The input files. These may or may not contain embedded device code. Each
  /// element must be either a relocatable object file, a static archive, or a
  /// shared object.
  MapVector<const Binary *, EmbDeviceCodes> bins;

private:
  /// Construct a fat binary from the embedded device code generated by the cuda
  /// tapir target.
  ///
  /// TODO: Write more documentation about the behavior of this function.
  Result linkNVFatBinary();

  /// Construct a fat binary from the embedded device code generated by the hip
  /// tapir target.
  ///
  /// TODO: Write more documentation about the behavior of this function.
  Result linkAMDGPUFatBinary();

public:
  DeviceCodeLinker(TTID tt);

  /// Add a binary that may contain embedded device code.
  Error add(const EmbDeviceCode &devCode);

  /// Link the embedded device code found in the object files that have been
  /// seen so far. Zero or more values will be returned - each containing the
  /// result of linking embedded device code generated by a specific tapir
  /// target. Each of the values will be a static archive.
  ///
  /// This does not behave in the same way as an actual linker. Roughly, this
  /// is implemented as follows:
  ///
  ///   Every input file is processed exactly once, even if it is added to the
  ///   linker more than once.
  ///
  ///     - If the input is an object file, the embedded device code is
  ///       extracted as an object file.
  ///
  ///     - If the input is a shared object, the embedded bitcode will be a
  ///       static archive. All elements of this archive must be device code
  ///       object files. All of these will be extracted.
  ///
  ///     - If the input a static archive, all members of the archive must be
  ///       device code object files. All of these will be extracted.
  ///
  ///   While extracting the object files, we ensure that the extracted files
  ///   have unique file names. Once all the inputs have been processed, the
  ///   extracted object files are combined into a single static archive.
  ///
  /// The description above assumes that all the embedded device code has been
  /// generated by a single tapir target. The same process is carried out for
  /// every tapir target for which embedded device code was found in the inputs.
  ///
  /// \param all If this is true, embedded device code found in the input shared
  ///            objects should be included in the final result.
  ///
  Expected<Result> linkStatic(bool all = false);

  /// Link the embedded device code found in the object files that have been
  /// seen so far and construct a fat binary for the device. Zero or more values
  /// will be returned - each containing the result of linking embedded device
  /// code generated by a specific tapir target.
  ///
  /// This will usually call an external utility to perform the actual link
  /// - for instance when linking device code generated by the cuda tapir
  /// target, nvlink performs the actual link. These external tools may have
  /// some limitations, so the behavior of this function is actually dependent
  /// on the capabilities of the external linker being used. See the
  /// documentation of the link*FatBinary functions for device-specific linking
  /// behavior. Currently, only linkNVFatBinary and linkAMDFatBinary have been
  /// implemented.
  Expected<Result> linkFatBinary();
};

} // namespace llvm

#endif // KITSUNE_LINKER_DEVICE_CODE_LINKER_H
