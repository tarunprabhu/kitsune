#ifndef KITSUNE_OBJECT_EMB_DEVICE_CODE_PARSER_H
#define KITSUNE_OBJECT_EMB_DEVICE_CODE_PARSER_H

#include "kitsune/Object/EmbDeviceCode.h"
#include "llvm/ADT/SmallVector.h"

namespace llvm {

namespace object {
class Archive;
class Binary;
class ObjectFile;
} // namespace object

class MemoryBuffer;

/// All the embedded device code objects found in a binary file. This object
/// should live at most as long as the binary file in which the embedded device
/// code objects were found.
class EmbDeviceCodes {
private:
  /// The binary file.
  const object::Binary &bin;

  /// If \ref bin is a static archive, the embedded device code will be a static
  /// archive obtained by linking the device code found in all members of the
  /// source archive. In this case, the generated archive is owned by this
  /// object, unlike the source binary which is owned by the caller. Device code
  /// from more than one tapir target may be present, so there may be multiple
  /// combined archives.
  SmallVector<std::unique_ptr<MemoryBuffer>, 1> archives;

  /// The device codes found in the binary. There could be more than one since
  /// device code generated by more than one tapir target could, in principle,
  /// be present in an object file.
  SmallVector<EmbDeviceCode, 1> codes;

public:
  using iterator = decltype(codes)::const_iterator;

private:
  EmbDeviceCodes(const object::Binary &bin) : bin(bin) {}

  /// Look for embedded device code in the given object file. Returns an error
  /// if any errors occurred when parsing the object file. Returns success even
  /// if no device code was found.
  Error parse(const object::ObjectFile &objFile);

  /// Look for embedded device code in the given archive. Returns an error if
  /// any errors occurred when parsing the archive. Returns success even if no
  /// device code was found.
  Error parse(const object::Archive &archive);

public:
  /// Get the embedded device code object generated by the given tapir target,
  /// if one exists.
  std::optional<EmbDeviceCode> get(TTID tt) const;

  iterator begin() const { return codes.begin(); }
  iterator end() const { return codes.end(); }

  /// If the object file did not contain any embedded device codes, this will
  /// return true.
  bool empty() const { return codes.empty(); }

  /// Parse all the sections containing embedded device code in an object file.
  /// Every tapir target that generates embedded device code inserts the device
  /// code into a specific section. The contents of the section vary
  /// depending on the type of the object file.
  ///
  ///   Relocatable object file (.o)
  ///
  ///     The section will contain a single binary "blob" - the format of which
  ///     is dependent on the specific device. For instance, in the case of
  ///     NVIDIA GPU's, this may be PTX or SASS. For AMDGPU, this will always be
  ///     AMDGPU machine code in the appropriate format for that plaform. On
  ///     Linux, for instance, this will be an ELF object. After parsing, this
  ///     single blob will be returned.
  ///
  ///   Dynamic Shared Object (.so, .dylib)
  ///
  ///     The section will contain a single binary "blob" which must be a static
  ///     archive consisting of the device code from all object files used to
  ///     build the DSO. After parsing, this single static archive will be
  ///     returned.
  ///
  ///   Static archive
  ///
  ///     When parsing a static archive, all members of the archive are expected
  ///     to be relocatable object files. Each object file will be treated
  ///     independently and must satisfy the constraints required of such files.
  ///     This embedded device code will be linked to form a static archive.
  ///
  /// If no sections containing embedded device code were found in the binary,
  /// std::nullopt is returned.
  ///
  static Expected<EmbDeviceCodes> parse(const object::Binary &bin);
};

} // namespace llvm

#endif // KITSUNE_OBJECT_EMB_DEVICE_CODE_PARSER_H
