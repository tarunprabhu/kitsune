#ifndef KITSUNE_OBJECT_OBJECT_UTILS_H
#define KITSUNE_OBJECT_OBJECT_UTILS_H

#include "kitsune/Core/Tapir.h"
#include "llvm/ADT/SmallVector.h"
#include "llvm/Support/Error.h"

namespace llvm {

namespace object {

class ObjectFile;

/// Check if an object file contains embedded device code generated by any tapir
/// target.
Expected<bool> hasEmbDeviceCode(const ObjectFile &obj);

/// Get the tapir targets that have generated embedded device code contained in
/// an object file.
Expected<SmallVector<TTID, 0>> getEmbDeviceCodeTTIDs(const ObjectFile &obj);

} // namespace object

} // namespace llvm

#endif // KITSUNE_OBJECT_OBJECT_UTILS_H
