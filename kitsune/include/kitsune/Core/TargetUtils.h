#ifndef KITSUNE_CORE_TARGET_UTILS_H
#define KITSUNE_CORE_TARGET_UTILS_H

#include "kitsune/Core/Tapir.h"
#include "llvm/Support/CodeGen.h"
#include "llvm/TargetParser/Host.h"

namespace llvm {

class MCTargetOptions;
class TapirTargetOptions;
class TargetMachine;
class TargetOptions;
class raw_ostream;

/// Create a target machine to optimize/compile device code generated by the
/// given tapir target. Currently, this is only relevant for the GPU tapir
/// targets. The machine is configured with the options in the
/// TapirTargetOptions object that is provided. The optimization level to use
/// in the target machine is derived from the optimization level set in the
/// \ref TapirTargetOptions.
TargetMachine *createTargetMachine(TTID tt, const TapirTargetOptions &tto);

/// Create a target machine to optimize/compile device code generated by the
/// given tapir target. Currently ,this is only relevant for the GPU tapir
/// targets. The machine is configured with the options in the
/// TapirTargetOptions object that is provided. The exception is the
/// optimization level which is provided explicitly.
TargetMachine *createTargetMachine(TTID tt, const TapirTargetOptions &opts,
                                   CodeGenOptLevel cgOptLevel);

/// Create a target machine for the given target triple. The target options
/// given to the target machine are left at  their defaults. This is intended to
/// be used when quickly generating an object file for the host.
TargetMachine *
createTargetMachine(StringRef triple = llvm::sys::getDefaultTargetTriple(),
                    CodeGenOptLevel cgOptLevel = CodeGenOptLevel::None,
                    Reloc::Model reloc = Reloc::PIC_,
                    CodeModel::Model codeModel = CodeModel::Small);

/// Dump the contents of the TargetOptions object to the given output
/// stream.
void dump(const TargetOptions &, raw_ostream &);

/// Dump the contents of the MCTargetOptions object to the given output stream.
void dump(const MCTargetOptions &, raw_ostream &);

} // namespace llvm

#endif // KITSUNE_CORE_TARGET_UTILS_H
