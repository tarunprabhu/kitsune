#include "kitrt.h"

#include <qthread.h>
#include <qthread/qloop.h>

#include <algorithm>
#include <cstdarg>
#include <cstdint>
#include <cstdio>

#define LABEL "kitqthr"

/// The function that is run on each thread. The last argument is a pointer to
/// a struct generated by the compiler where all the data needed by the
/// function is bundled together. start and end are the starts and ends of the
/// iteration space that must be split across the threads.
using KitQthrThrdFn = void (*)(const unsigned long start,
                               const unsigned long end, void *args);

/// Launch some number of threads each of which will execute some number of
/// iterations in the space [\ref start, \ref end). Terminates the program with
/// a fatal error if any thread could not be launched. This blocks until all
/// threads have completed.
///
/// \param f The function to execute on each thread
/// \param start The start index of the iteration space
/// \param end The value one greater than the last index of the iteration space
/// \param grainSize The grainSize
/// \param args A struct containing data to be passed to \p f
extern "C" void __kitqthr_launch(KitQthrThrdFn f, int64_t start, int64_t end,
                                 int64_t grainSize, void *args) {
  __kitrt_message(LABEL, "Launching threads");
  __kitrt_message(LABEL, "Iteration range: [%ld, %ld)", start, end);

  // TODO: In some cases, it may be beneficial to use qt_loop_balance() here
  // instead of qt_loop_balance_simple. We should run some tests to see if this
  // is ever the case.
  qt_loop_balance_simple(start, end, f, args);

  __kitrt_message(LABEL, "Joined threads");
}

/// Initialize kitsune's qthreads runtime as well as the actual qthreads
/// runtime.
extern "C" void __kitqthr_initialize(void) {
  // Initialize the components of kitsune's runtime that are shared by the
  // tapir-target-specific components.
  __kitrt_initialize();
  __kitrt_message(LABEL, "Initializing Kitsune qthreads runtime");

  qthread_initialize();

  __kitrt_message(LABEL, "Number of shepherds = %d", qthread_num_shepherds());
  __kitrt_message(LABEL, "Number of workers = %d", qthread_num_workers());
  __kitrt_message(LABEL, "Initialized Kitsune qthreads runtime");
}

/// Finalize kitsune's qthreads runtime, as well as qthreads runtime.
extern "C" void __kitqthr_finalize(void) {
  __kitrt_message(LABEL, "Finalizing Kitsune qthreads runtime");

  qthread_finalize();

  __kitrt_message(LABEL, "Finalized Kitsune qthreads runtime");
}
